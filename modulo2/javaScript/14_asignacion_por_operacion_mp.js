vacantesDisponibles += 5;    // vacantesDisponibles = vacantesDisponibles + 5  → 15
vacantesDisponibles -= 3;    // vacantesDisponibles = vacantesDisponibles - 3  → 12
vacantesDisponibles *= 2;    // vacantesDisponibles = vacantesDisponibles * 2  → 24
vacantesDisponibles /= 4;    // vacantesDisponibles = vacantesDisponibles / 4  → 6
vacantesDisponibles %= 4;    // vacantesDisponibles = vacantesDisponibles % 4  → 2
vacantesDisponibles **= 3;   // vacantesDisponibles = vacantesDisponibles ** 3 → 8

